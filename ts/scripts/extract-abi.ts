// Regenerates src/anchorAbi.ts from the Foundry build output. Run `forge build` in ../contracts first.
import { readFileSync, writeFileSync } from "node:fs";

const artifact = JSON.parse(
  readFileSync(new URL("../../contracts/out/LightsphereAnchor.sol/LightsphereAnchor.json", import.meta.url), "utf8"),
);
const body = `// Generated by scripts/extract-abi.ts from contracts/out. Do not edit.\nexport const anchorAbi = ${JSON.stringify(
  artifact.abi,
  null,
  2,
)} as const;\n`;
writeFileSync(new URL("../src/anchorAbi.ts", import.meta.url), body);
console.log(`wrote src/anchorAbi.ts (${artifact.abi.length} entries)`);
